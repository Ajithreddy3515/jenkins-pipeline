#!/usr/bin/env bash

###############################################################################
# Common Utility Functions
###############################################################################

timestamp()
{
    date "+%Y-%m-%d %H:%M:%S"
}

###############################################################################

command_exists()
{
    command -v "$1" >/dev/null 2>&1
}

###############################################################################

directory_exists()
{
    [[ -d "$1" ]]
}

###############################################################################

file_exists()
{
    [[ -f "$1" ]]
}

###############################################################################

ensure_directory()
{
    local directory="$1"

    if [[ ! -d "$directory" ]]; then
        mkdir -p "$directory"
    fi
}

###############################################################################

remove_file()
{
    local file="$1"

    [[ -f "$file" ]] && rm -f "$file"
}

###############################################################################

remove_directory()
{
    local directory="$1"

    [[ -d "$directory" ]] && rm -rf "$directory"
}


###############################################################################

require_command()
{
    local command="$1"

    if ! command_exists "$command"; then
        echo "ERROR: Required command not found: ${command}"
        exit 1
    fi
}

###############################################################################

print_line()
{
    printf '%*s\n' 80 '' | tr ' ' '='
}
