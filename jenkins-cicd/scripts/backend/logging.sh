#!/usr/bin/env bash

###############################################################################
# Logging Functions
###############################################################################

log()
{
    local level="$1"
    shift

    local message="$*"

    printf "[%s] [%-5s] %s\n" \
        "$(timestamp)" \
        "$level" \
        "$message" | tee -a "$DEPLOY_LOG"
}

###############################################################################

info()
{
    log "INFO" "$@"
}

###############################################################################

warn()
{
    log "WARN" "$@"
}

###############################################################################

error()
{
    log "ERROR" "$@"
}

###############################################################################

debug()
{
    log "DEBUG" "$@"
}
